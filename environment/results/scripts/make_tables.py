"""Build the comparison tables in results/README.md from the benchmark data.

Usage: python environment/results/scripts/make_tables.py > environment/results/tables.md
Reads environment/results/retrieval_benchmark (runs, judgments); no API calls.
"""

from __future__ import annotations

import statistics
from collections.abc import Callable
from pathlib import Path

from bench.config import BenchSettings
from bench.report import (
    METRICS,
    MONEY,
    PERCENT,
    Score,
    build_scores,
    comparable,
    estimate,
    paired_difference,
)
from bench.schemas import Item
from bench.stats import Estimate
from bench.workspace import Workspace, read_models

WS = Workspace(Path(__file__).resolve().parents[1] / "retrieval_benchmark")
CONFIGS = [
    "current",
    "current_fixed",
    "improved_1to4",
    "improved_1to5",
    "improved_1to6",
    "openrouter_search",
    "openrouter_search_improved",
]
LABELS = {
    "current": "Current (original)",
    "current_fixed": "Current + Europe PMC fix",
    "improved_1to4": "Changes 1–4",
    "improved_1to5": "Changes 1–5",
    "improved_1to6": "Changes 1–6",
    "openrouter_search": "OpenRouter search",
    "openrouter_search_improved": "OpenRouter search, improved",
}
QUALITY = [
    "mean_relevance",
    "p_relevant",
    "u_hit",
    "u_precision",
    "c_hit",
    "c_precision",
    "majority_correct",
    "answer_close",
    "answer_category",
    "answered",
]
PAIRS = [
    ("improved_1to4", "openrouter_search"),
    ("improved_1to4", "current_fixed"),
    ("current_fixed", "current"),
    ("improved_1to5", "improved_1to4"),
    ("improved_1to6", "improved_1to5"),
    ("openrouter_search_improved", "openrouter_search"),
    ("improved_1to4", "openrouter_search_improved"),
]
BOOT = 2000


def fmt(metric: str, value: float | None) -> str:
    if value is None:
        return "–"
    if metric in PERCENT:
        return f"{value * 100:.0f}%"
    if metric in MONEY:
        return f"${value:.5f}"
    return f"{value:.2f}"


def fmt_diff(metric: str, est: Estimate) -> str:
    if est.mean is None:
        return "–"
    lo, hi = est.low, est.high
    scale, unit, digits = (100.0, " pts", 0) if metric in PERCENT else (1.0, "", 2)
    body = f"{est.mean * scale:+.{digits}f}{unit}"
    if lo is None or hi is None:
        return body
    ci = f" [{lo * scale:+.{digits}f}, {hi * scale:+.{digits}f}]"
    return f"**{body}{ci}**" if lo > 0 or hi < 0 else f"{body}{ci}"


def main() -> None:
    items = read_models(WS.items, Item)
    judge = BenchSettings().judge_model
    all_scores = build_scores(WS, items, CONFIGS, judge)
    scores, excluded = comparable(all_scores, CONFIGS)
    n = len({s.item_id for s in scores})
    n_a = len({s.item_id for s in scores if s.question_set == "A"})
    print(
        f"<!-- generated by environment/results/scripts/make_tables.py; {n} questions "
        f"({n_a} with a hidden value); excluded: {', '.join(sorted(excluded))} -->\n"
    )

    print(
        "### Quality ("
        + f"{n} questions on which every method retrieved; {n_a} with a hidden value)\n"
    )
    print("| Metric | " + " | ".join(LABELS[c] for c in CONFIGS) + " |")
    print("|---|" + "---|" * len(CONFIGS))
    for metric in QUALITY:
        label, _, sets = METRICS[metric]
        in_sets = [s for s in scores if s.question_set in sets]
        cells = [
            fmt(metric, estimate([s for s in in_sets if s.config == c], metric,
                                 n_boot=10, seed=1).mean)
            for c in CONFIGS
        ]  # fmt: skip
        print(f"| {label} | " + " | ".join(cells) + " |")

    print("\n### Cost and time (all 50 questions, including excluded ones)\n")
    print("| | " + " | ".join(LABELS[c] for c in CONFIGS) + " |")
    print("|---|" + "---|" * len(CONFIGS))
    per = {c: [s for s in all_scores if s.config == c] for c in CONFIGS}

    def total(r: list[Score]) -> float:
        return sum(s.total_cost for s in r)

    cost_rows: list[tuple[str, Callable[[list[Score]], str]]] = [
        ("Retrieval: search fees and search/rerank LLM, 50 questions",
         lambda r: f"${sum(s.retrieval_cost for s in r):.4f}"),
        ("medsim LLM (Stages A–C), 50 questions",
         lambda r: f"${sum(s.pipeline_cost for s in r):.4f}"),
        ("**Total, 50 questions**", lambda r: f"**${total(r):.4f}**"),
        ("**Total per question**", lambda r: f"**${total(r) / len(r):.5f}**"),
        ("Projected per 1,000 questions", lambda r: f"${total(r) / len(r) * 1000:.2f}"),
        ("**Average time per question**",
         lambda r: f"**{statistics.mean(s.wall_time_s for s in r):.0f} s**"),
        ("… of which medsim's LLM calls (Stages A–C), average",
         lambda r: f"{statistics.mean(min(s.llm_time_s, s.wall_time_s) for s in r):.0f} s"),
        ("… of which retrieval (everything else), average",
         lambda r: f"{statistics.mean(max(s.wall_time_s - s.llm_time_s, 0) for s in r):.0f} s"),
        ("Median time per question",
         lambda r: f"{statistics.median(s.wall_time_s for s in r):.0f} s"),
    ]  # fmt: skip
    for label, fn in cost_rows:
        print(f"| {label} | " + " | ".join(fn(per[c]) for c in CONFIGS) + " |")

    print("\n### Paired differences (95% CI; bold = interval excludes zero)\n")
    metrics = ["p_relevant", "u_hit", "u_precision", "c_hit", "majority_correct", "answer_close"]
    print("| Comparison | " + " | ".join(METRICS[m][0] for m in metrics) + " |")
    print("|---|" + "---|" * len(metrics))
    for a, b in PAIRS:
        cells = []
        for m in metrics:
            rows = [s for s in scores if s.question_set in METRICS[m][2]]
            cells.append(fmt_diff(m, paired_difference(rows, m, b, a, n_boot=BOOT, seed=11)))
        print(f"| {LABELS[a]} − {LABELS[b]} | " + " | ".join(cells) + " |")


if __name__ == "__main__":
    main()
